  /** 解析年份：今年/明年/去年/YYYY年；无年份指示 → 当前年份 */
  function parseYear(input, now) {
    var year = now.getFullYear();
    if (/去年/.test(input)) return year - 1;
    if (/明年/.test(input)) return year + 1;
    if (/今年/.test(input)) return year;
    var m = input.match(/(\d{4})年/);
    return m ? parseInt(m[1], 10) : year;
  }

  /** "YYYY-MM-DD" → "M月D日（周X）"；跨年时带年份 */
  function fmtDate(dateStr, now) {
    var parts = dateStr.split("-");
    var y = parseInt(parts[0], 10), mo = parseInt(parts[1], 10), d = parseInt(parts[2], 10);
    var date = new Date(y, mo - 1, d);
    var w = WEEK[date.getDay()];
    if (y !== now.getFullYear()) return y + "年" + mo + "月" + d + "日（" + w + "）";
    return mo + "月" + d + "日（" + w + "）";
  }

